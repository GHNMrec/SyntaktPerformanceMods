"""Mod midi-guard: builds patch.json from mg.c (see the comment at the top of mg.c).

    python mods/midi-guard/make_patch.py      # ColdFire gcc 13 (WSL on Windows, native on Linux)

Generates mg_tables.h from the stock OS: the descriptor words the mods change (min, max, default,
names) and the construction recipe of the 16 objects (emulated stock initializer, recipe.py).
Links mg.c in the mod area at +0x8800 (up to +0xA000; +0x5000 is SY FM4's since TEST12). Build it before
mods/vparams.

With mods/fm4/patch.json present (build mods/fm4 first) it also builds the SY FM4 scope (mg.c, MG_FM4): ids
254-261 stay the MIDI machine's CC VALUE knobs and are lent to FM4's page 2 only while it is on screen, with
three OS hooks: the generic page draw prologue 0x4003A244 and the CC / NRPN lookups 0x400A6796 / 0x400A6816.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path[:0] = [str(HERE), str(REPO / "tools" / "unpack"), str(REPO / "tools" / "build")]
import eft  # noqa: E402
import modarea_layout  # noqa: E402
import recipe  # noqa: E402

LOAD = 0x4000_0400
DESC, REC = 0x4022_D83C, 52
CODE, CODE_END = modarea_layout.RAM + 0x8800, modarea_layout.RAM + 0xA000
FM4_SPEC = REPO / "mods" / "fm4" / "patch.json"
# SY FM4 scope hooks: (address, stock bytes, symbol, nops)
FM4_HOOKS = [(0x4003_A244, "4fefffb048d77cfc", "mg_draw_hook", 1),   # generic page draw prologue (8 B)
             (0x400A_6796, "2f0a2f02747f", "mg_cc_filter", 0),       # OS CC lookup
             (0x400A_6816, "2f0a2f02222f000c", "mg_nrpn_filter", 1)]  # OS NRPN lookup
IDS = list(range(246, 254)) + list(range(262, 270)) + [445, 446] + [443, 402, 406, 412] + [442] + [431, 432]
# MIDI SRC, CC SELECT; IMPULSE REP, NUM (beat-repeat RPT2, RPT); IMPULSE SHP, COL of three drum machines
# (master-filter TYPE, FREQ, RESO, DRV); IMPULSE HOLD (master-filter ON/OFF); NLEV, NDEC of a fourth drum machine
# (group 31: master-filter TRIM, CMP)
EXTRA_IDS = (445, 446, 443, 402, 406, 412, 442, 431, 432)   # outside 246..269: vparams lists them one by one
DESC_WORDS = (2, 3, 4, 10, 12)                         # min, max, default, long name, short name
TOOLS = "~/tools/m68k/root"
CFLAGS = ("-mcpu=54418 -O2 -ffreestanding -fno-builtin -nostdlib -fno-pic -fno-common "
          "-fno-tree-loop-distribute-patterns -Wall -Wextra")


def sh(cmd: str) -> str:
    """Run a shell command in WSL (Windows) or locally (Linux)."""
    args = (["wsl.exe", "-e", "bash", "-lc", cmd] if os.name == "nt" else ["bash", "-lc", cmd]) if os.name == "nt" else ["bash", "-lc", cmd]
    r = subprocess.run(args, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(f"command failed:\n{cmd}\n{r.stderr}")
    return r.stdout + r.stderr


def tables(sec3: bytes, fm4: dict | None) -> str:
    rec = recipe.recipe(sec3, IDS)
    lines = ["/* generated by mods/midi-guard/make_patch.py from the stock Syntakt OS 1.41 */",
             f"#define NID {len(IDS)}",
             "static const unsigned short mg_ids[NID] = {" + ", ".join(map(str, IDS)) + "};",
             "/* stock descriptor words per id: min, max, default, long name, short name */",
             "#define MG_DESC_STOCK { \\"]
    for i in IDS:
        w = struct.unpack(">13I", sec3[DESC - LOAD + REC * i:DESC - LOAD + REC * (i + 1)])
        lines.append("    {" + ", ".join(f"{w[k]:#010x}u" for k in DESC_WORDS) + f"}}, /* {i} */ \\")
    lines.append("}")
    lines.append("/* stock objects: encoder type, value prototype (16 B, memcpy), formatter, graphic, style */")
    lines.append("static const unsigned int mg_recipe[NID][5] = {")
    for i in IDS:
        t, pod, fmt, gfx, _p52, sty = rec[i]
        lines.append(f"    {{{t}u, {pod:#010x}u, {fmt:#010x}u, {gfx:#010x}u, {sty:#010x}u}}, /* {i} */")
    lines.append("};")
    if fm4:
        lines.append("/* SY FM4 (mods/fm4): FM4's descriptor rows for 254-261 (RC2) and its object donors */")
        lines.append("#define FM4_ROWS { \\")
        for i in fm4["ids"]:
            w = struct.unpack(">13I", bytes.fromhex(fm4["rows"][str(i)]))
            lines.append("    {" + ", ".join(f"{x:#010x}u" for x in w) + f"}}, /* {i} */ \\")
        lines.append("}")
        lines.append("#define FM4_DONORS {" + ", ".join(map(str, fm4["donors"])) + "}")
    return "\n".join(lines) + "\n", rec


def main() -> None:
    stock = REPO / "firmware" / "Syntakt_OS1.42.syx"
    sec3 = eft.unpack(stock, REPO / "unpacked" / stock.stem, ids=[3])[3].read_bytes()
    fm4 = json.loads(FM4_SPEC.read_text(encoding="utf-8")) if FM4_SPEC.exists() else None
    if fm4 and fm4["ids"] != list(range(254, 262)):
        raise SystemExit("mods/fm4: unexpected ids")
    header, rec = tables(sec3, fm4)
    with tempfile.TemporaryDirectory(prefix="midi-guard-") as tmp:
        tmp = Path(tmp)
        shutil.copy(HERE / "mg.c", tmp / "mg.c")
        (tmp / "mg_tables.h").write_text(header, encoding="utf-8")
        w = eft.to_wsl_path(tmp)
        env = f"R={TOOLS}; export LD_LIBRARY_PATH=$R/usr/lib/x86_64-linux-gnu; cd {w}; "
        gcc = "$R/usr/bin/m68k-linux-gnu-gcc-13 -B$R/usr/libexec/gcc/m68k-linux-gnu/13/ -B$R/usr/bin/m68k-linux-gnu-"
        warn = sh(env + f"{gcc} {CFLAGS}{' -DMG_FM4' if fm4 else ''} -c mg.c -o mg.o")
        if warn.strip():
            raise SystemExit(f"compiler warnings:\n{warn}")
        sh(env + f"$R/usr/bin/m68k-linux-gnu-ld -N -Ttext={CODE:#x} -e mg_ensure -o mg.elf mg.o")
        undef = sh(env + "$R/usr/bin/m68k-linux-gnu-nm -u mg.elf").strip()
        if undef:
            raise SystemExit(f"external symbols not allowed (libgcc?): {undef}")
        heads = sh(env + "$R/usr/bin/m68k-linux-gnu-objdump -h mg.elf")
        for name, size in re.findall(r"^\s*\d+\s+(\.\S+)\s+([0-9a-f]+)", heads, re.M):
            if name in (".bss", ".sbss") and int(size, 16):
                raise SystemExit("mg.c must not have .bss variables")
        sh(env + "$R/usr/bin/m68k-linux-gnu-objcopy -O binary -j .text -j .rodata -j .data mg.elf mg.bin")
        syms = {}
        for line in sh(env + "$R/usr/bin/m68k-linux-gnu-nm mg.elf").splitlines():
            p = line.split()
            if len(p) == 3:
                syms[p[2]] = int(p[0], 16)
        blob = (tmp / "mg.bin").read_bytes()
    if CODE + len(blob) > CODE_END:
        raise SystemExit(f"mg.bin too large: {len(blob)} B")
    img = modarea_layout.IMG + (CODE - modarea_layout.RAM)
    patches = [{"section": 3, "addr": f"{img:#010X}", "len": len(blob), "append": True, "hex": blob.hex(),
                "ram": f"{CODE:#010x}", "what": "(area mod) mg_ensure, stock shadow tables (mg.c)"}]
    names = ["mg_ensure", "mg_ctx", "mg_swaps", "mg_built"]
    if fm4:
        for addr, orig, sym, nops in FM4_HOOKS:
            old = sec3[addr - LOAD:addr - LOAD + len(orig) // 2]
            if old.hex() != orig:
                raise SystemExit(f"{addr:#x}: unexpected bytes {old.hex()}")
            code = struct.pack(">HI", 0x4EF9, syms[sym]) + b"\x4e\x71" * nops
            patches.append({"section": 3, "addr": f"{addr:#010X}", "len": len(code),
                            "expect_sha256": hashlib.sha256(old).hexdigest(), "hex": code.hex(),
                            "what": f"SY FM4 scope: jmp {sym}" + (" ; nop" if nops else "")})
        names += ["mg_fm4", "mg_fm4_built", "mg_fm4_swaps", "mg_fm4_drops", "mg_fm4_ensure", "mg_fm4_view",
                  "mg_fm4_draw", "mg_draw_hook", "mg_cc_filter", "mg_nrpn_filter"]
    spec = {
        "name": "midi-guard", "os": "1.42", "requires": ["modarea"],
        "description": "Keeps fx3, master-comp, beat-repeat and master-filter off the stock pages whose ids they "
                       "borrow (MIDI machine SRC and CC SELECT 246-253, 262-269; IMPULSE REP/NUM/SHP/HOLD 445/446/443/442; COL "
                       "402/406/412; NLEV/NDEC 431/432): those ids are the mods' only on the FX track (and the FX3 page); elsewhere the "
                       "stock "
                       "descriptors, objects and kit functions are restored. The context follows the active track of "
                       "the UI page views (switch called by vparams from is-kit)." +
                       (" SY FM4 scope: ids 254-261 (MIDI CC VALUE VAL1-VAL8) are FM4's page 2 knobs only while "
                        "that page is on screen (draw prologue 0x4003A244, vparams); CC/NRPN lookups for them are "
                        "suppressed meanwhile." if fm4 else ""),
        "generated_by": "mods/midi-guard/make_patch.py",
        "ids": IDS,
        "extra_ids": list(EXTRA_IDS),
        "recipe": {str(i): [f"{v:#010x}" for v in rec[i]] for i in IDS},
        "fm4": bool(fm4),
        "symbols": {k: f"{syms[k]:#010x}" for k in names},
        "patches": patches,
    }
    (HERE / "patch.json").write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"patch.json: {len(blob)} B at {CODE:#x}..{CODE + len(blob):#x}; "
          f"mg_ensure {syms['mg_ensure']:#x}, mg_ctx {syms['mg_ctx']:#x}")


if __name__ == "__main__":
    main()
